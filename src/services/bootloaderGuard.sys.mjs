/*
  Sine is loaded by config.js and defaults/pref/config-prefs.js, which live in
  the browser's install directory. Updating the browser by replacing that
  directory (tarball reinstalls, update scripts, package moves) deletes them,
  so Sine silently stops loading and the browser's own mods page comes back.

  While Sine is running those files are known to be good, so this service:
    1. backs them up into the profile, and
    2. installs a systemd user path unit that watches the install directory
       and copies the backups back whenever the files go missing.

  Set `sine.bootloader-guard.enabled` to false to turn this off. Removing the
  units is `systemctl --user disable --now sine-bootloader-*.path`.
*/

import ucAPI from "../utils/uc_api.sys.mjs";

const ENABLED_PREF = "sine.bootloader-guard.enabled";

/** Bootloader files, relative to the install directory. */
const BOOTLOADER_FILES = [["config.js"], ["defaults", "pref", "config-prefs.js"]];

const RESTORE_SCRIPT = `#!/bin/sh
# Generated by Sine. Restores Sine's bootloader into a browser install
# directory after an update removed it.
# Usage: restore-bootloader.sh <backup dir> <install dir>
backup="$1"
install="$2"

# Let an in-progress update finish writing before checking.
sleep 3

# Only restore into a complete browser install.
[ -f "$install/application.ini" ] || exit 0

restore() {
  if [ -f "$1" ] && [ ! -f "$2" ]; then
    mkdir -p "$(dirname "$2")" && cp "$1" "$2" && echo "Restored $2"
  fi
}

restore "$backup/config.js" "$install/config.js"
restore "$backup/config-prefs.js" "$install/defaults/pref/config-prefs.js"
exit 0
`;

/**
 * Returns a short, stable hexadecimal hash of a string.
 *
 * @param {string} str - The string to hash.
 * @returns {string} An 8-character hexadecimal hash.
 */
const hash = (str) => {
  let h = 7;
  for (const char of str) {
    h = (h * 31 + char.codePointAt(0)) % 0x100000000;
  }
  return h.toString(16).padStart(8, "0");
};

/**
 * Quotes a path for a systemd unit file.
 *
 * @param {string} path - The path to quote.
 * @returns {string} The quoted path.
 */
const quote = (path) => `"${path.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;

/**
 * Writes a file only if its contents changed.
 *
 * @param {string} path - The file path.
 * @param {string} contents - The new contents.
 * @param {number} [permissions] - Unix permissions to apply.
 * @returns {Promise<boolean>} True if the file was written.
 */
const writeIfChanged = async (path, contents, permissions) => {
  const current = await IOUtils.readUTF8(path).catch(() => null);
  if (current === contents) {
    return false;
  }
  await IOUtils.makeDirectory(PathUtils.parent(path), { ignoreExisting: true });
  await IOUtils.writeUTF8(path, contents);
  if (permissions) {
    await IOUtils.setPermissions(path, permissions);
  }
  return true;
};

/**
 * Checks whether the current user can write to a directory.
 *
 * @param {string} dir - The directory to check.
 * @returns {Promise<boolean>} True if the directory is writable.
 */
const isWritable = async (dir) => {
  const probe = PathUtils.join(dir, `.sine-write-test-${Date.now()}`);
  try {
    await IOUtils.writeUTF8(probe, "");
    await IOUtils.remove(probe);
    return true;
  } catch {
    return false;
  }
};

export default {
  /** Backs up the bootloader and installs the restore watcher. */
  async init() {
    if (ucAPI.utils.os !== "lin" || !Services.prefs.getBoolPref(ENABLED_PREF, true)) {
      return;
    }
    // Sandboxed installs cannot reach systemd, and their install directory is read-only.
    if (Services.env.get("FLATPAK_ID") || Services.env.get("SNAP")) {
      return;
    }

    const installDir = Services.dirsvc.get("GreD", Ci.nsIFile).path;
    const backupDir = PathUtils.join(ucAPI.utils.chromeDir, "sine-bootloader");

    // Sine is running, so the files in the install directory are known to work.
    await IOUtils.makeDirectory(backupDir, { ignoreExisting: true });
    await Promise.all(
      BOOTLOADER_FILES.map(async (parts) => {
        const source = PathUtils.join(installDir, ...parts);
        if (await IOUtils.exists(source)) {
          await IOUtils.copy(source, PathUtils.join(backupDir, parts.at(-1)));
        }
      })
    );

    // A package manager keeps files it does not own when upgrading a root-owned
    // install, and the user could not restore into it anyway.
    if (!(await isWritable(installDir))) {
      return;
    }

    const home = Services.dirsvc.get("Home", Ci.nsIFile).path;
    const dataHome = Services.env.get("XDG_DATA_HOME") || PathUtils.join(home, ".local", "share");
    const configHome = Services.env.get("XDG_CONFIG_HOME") || PathUtils.join(home, ".config");

    const script = PathUtils.join(dataHome, "sine", "restore-bootloader.sh");
    const unit = `sine-bootloader-${hash(`${installDir}\n${backupDir}`)}`;
    const unitDir = PathUtils.join(configHome, "systemd", "user");

    const service = `# Generated by Sine.
[Unit]
Description=Restore Sine's bootloader in ${installDir}

[Service]
Type=oneshot
ExecStart=/bin/sh ${quote(script)} ${quote(backupDir)} ${quote(installDir)}

[Install]
WantedBy=default.target
`;
    const path = `# Generated by Sine.
[Unit]
Description=Watch ${installDir} for updates that remove Sine's bootloader

[Path]
PathChanged=${installDir}
PathChanged=${PathUtils.join(installDir, "defaults", "pref")}
Unit=${unit}.service
TriggerLimitBurst=1000

[Install]
WantedBy=default.target
`;

    const changed = [
      await writeIfChanged(script, RESTORE_SCRIPT, 0o755),
      await writeIfChanged(PathUtils.join(unitDir, `${unit}.service`), service),
      await writeIfChanged(PathUtils.join(unitDir, `${unit}.path`), path),
    ].some(Boolean);
    if (!changed) {
      return;
    }

    const { Subprocess } = ChromeUtils.importESModule("resource://gre/modules/Subprocess.sys.mjs");
    const systemctl = await Subprocess.pathSearch("systemctl").catch(() => null);
    if (!systemctl) {
      return;
    }
    const run = async (...args) => {
      const proc = await Subprocess.call({
        command: systemctl,
        arguments: ["--user", ...args],
        environmentAppend: true,
        stderr: "stdout",
      });
      const output = await proc.stdout.readString();
      const { exitCode } = await proc.wait();
      if (exitCode !== 0) {
        throw new Error(`systemctl --user ${args.join(" ")} failed: ${output.trim()}`);
      }
    };
    await run("daemon-reload");
    await run("enable", "--now", `${unit}.path`, `${unit}.service`);
  },
};
